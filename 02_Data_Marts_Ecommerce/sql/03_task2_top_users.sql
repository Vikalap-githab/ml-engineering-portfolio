/* Выводы по Задаче 2: Топ-15 пользователей по среднему чеку
 *
 * Точка отсчёта:
 * - Средний чек по всей витрине составляет ~3 100–3 300 руб.
 * - Средний чек лидера топа превышает 14 000 руб. — разница в 4–4.5 раза.
 * - Это классический VIP-сегмент ("киты"): малая доля клиентов, но непропорционально
 *   большая доля выручки.
 *
 * Ключевой инсайт:
 * - Клиенты из топа имеют от 3 до 15 заказов. Ценность создаётся в первую очередь
 *   за счёт размера чека, а не частоты покупок (у большинства из топа всего 3–7 заказов).
 * - Это означает, что бизнесу выгоднее работать над увеличением среднего чека существующих
 *   клиентов (cross-sell, up-sell), чем пытаться искусственно увеличить частоту.
 *
 * Рекомендации для бизнеса:
 * - Выделить этих 15 пользователей в отдельный VIP-сегмент в CRM.
 * - Предложить персональные условия: ранний доступ к распродажам, персональный менеджер,
 *   эксклюзивные предложения.
 * - Провести анализ их поведения (категории товаров, регионы, способы оплаты),
 *   чтобы найти похожих пользователей и масштабировать их паттерн через таргетированную рекламу.
 */

SELECT 
    RANK() OVER (ORDER BY avg_order_cost DESC) AS rank,
    user_id,
    total_orders,
    avg_order_cost
FROM ds_ecom.product_user_features
WHERE total_orders >= 3
ORDER BY avg_order_cost DESC
LIMIT 15;
