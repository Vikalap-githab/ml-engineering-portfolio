/* Выводы по Задаче 1: Сегментация пользователей
 *
 * Ключевые инсайты:
 * - Эффект "длинного хвоста": Подавляющее большинство пользователей (~97%, более 60 тыс. человек)
 *   совершают только один заказ. Это указывает на системную проблему с удержанием (retention).
 * - Обратная зависимость чека и лояльности: Чем чаще пользователь возвращается, тем ниже
 *   его средний чек (с ~3 305 руб. до ~1 244 руб.).
 *
 * Гипотезы снижения чека у лояльных клиентов:
 * 1. Смена паттерна покупок: переход от дорогих разовых покупок (техника, мебель)
 *    к регулярным, но более дешёвым (расходники, повседневные товары).
 * 2. Использование механик: лояльные пользователи активнее применяют промокоды,
 *    программы лояльности или ждут распродаж, искусственно занижая средний чек.
 *
 * Оговорка по статистической значимости:
 * - Сегменты «6–10 заказов» и «11+ заказов» содержат крайне малую выборку (5 и 1 пользователь).
 *   Средний чек в этих группах отражает индивидуальную историю, а не рыночный тренд (шум).
 *
 * Рекомендации для бизнеса:
 * - Сместить фокус с массового привлечения на удержание (внедрить триггерные рассылки
 *   и бонусы на второй заказ).
 * - Провести качественный анализ (deep dive) единственного клиента из сегмента 11+,
 *   чтобы составить портрет "идеального постоянного покупателя" и масштабировать его опыт.
 */

WITH user_segments AS (
    SELECT 
        user_id,
        total_order_costs,
        total_orders,
        CASE
            WHEN total_orders = 1 THEN '1 заказ'
            WHEN total_orders >= 2 AND total_orders <= 5 THEN '2—5 заказов'
            WHEN total_orders >= 6 AND total_orders <= 10 THEN '6–10 заказов'   
            ELSE '11 и более заказов' 
        END AS segment
    FROM ds_ecom.product_user_features
)
SELECT 
    segment,
    COUNT(DISTINCT user_id) AS user_count,
    ROUND(AVG(total_orders), 2) AS avg_orders,
    ROUND(SUM(total_order_costs)::NUMERIC / NULLIF(SUM(total_orders), 0), 2) AS avg_order_cost
FROM user_segments
GROUP BY segment
ORDER BY MIN(total_orders);
